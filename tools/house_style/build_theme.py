# The colours the reader can choose, each with what it sets the body's colour scheme to.
COLOUR_SCHEMES = {"Light": "light", "Dark": "dark"}


def house_style_module(data, faces, advances):
    """house_style.py: the page's stylesheet as one <style> element, in lines
    short enough to read a diff of, as glyph_font.py holds its fonts, and the
    interface face's advances, which a grid's column widths are read from."""
    text = "<style>" + page_css(data, faces) + "</style>"
    width = 96
    lines = [text[i:i + width] for i in range(0, len(text), width)]
    body = "\n".join("    " + json.dumps(line, ensure_ascii=False) for line in lines)
    schemes = "\n".join(f'    "{choice}": "<style>body{{color-scheme:{scheme};}}</style>",'
                        for choice, scheme in COLOUR_SCHEMES.items())
    held = "\n".join(f"    {advance}: {json.dumps(chars, ensure_ascii=False).replace(chr(0xA0), chr(0x5C) + "u00a0")}," for advance, chars in advances.items())
    report = "\n".join("    " + json.dumps(line + "\n", ensure_ascii=False) for line in export_css(data).splitlines())
    wheel = pprint.pformat({mode: palettes(t) for mode, t in data["modes"].items()}, width=100, sort_dicts=False, compact=True)
    return ('# Zīj. Copyright (C) 2026 Dār al-Ḥikma.\n'
            '# Licensed under the GNU Affero General Public License, version 3: see LICENSE.\n'
            '"""Generated by tools/house_style/build_theme.py from its tokens.json. Edit that, never this file.\n'
            '\n'
            'The page\'s own stylesheet, one <style> element, which app.py emits once the door has let\n'
            'a session in. It holds what the theme in .streamlit/config.toml has no key for: which face a\n'
            'passage draws in by where it stands, tables and definition lists, small text in a colour the page itself\n'
            'resolves under either theme, and\n'
            'Zij Interface Marks, the letters IBM Plex Sans Condensed lacks, composed from that font\'s\n'
            'own letter and mark and embedded as a data URI, as glyph_font.py embeds the symbol font\n'
            '(its licence and notice: fonts/OFL.txt). It holds as well the colours and the stack the\n'
            'pictures draw in, which wheel.py reads, and the HTML report\'s stylesheet, which\n'
            'export_html.py reads.\n'
            '"""\n'
            'PAGE_STYLE = (\n' + body + '\n)\n\n'
            '# A dialog or a popover under colours the reader has chosen: emitted after PAGE_STYLE, whose\n'
            '# rule for the same element answers the computer.\n'
            'PAGE_COLOUR_SCHEME = {\n' + schemes + '\n}\n\n'
            '# The interface face\'s characters by their advance, in thousandths of an em.\n'
            'CELL_ADVANCES = {\n' + held + '\n}\n\n'
            '# The colours a picture is drawn in, by the mode it is drawn for.\n'
            'WHEEL_PALETTES = ' + wheel + '\n\n'
            '# The stack a picture draws in.\n'
            'PICTURE_STACK = ' + json.dumps(picture_stack(data["type"]["stacks"]["interface"])) + '\n\n'
            '# The HTML report\'s stylesheet, without its faces (saved_faces.py).\n'
            'EXPORT_STYLE = (\n' + report + '\n)\n')


def write_all(data, faces, advances, repo):
    config_path = repo / ".streamlit" / "config.toml"
    existing = config_path.read_text(encoding="utf-8")
    head = existing.split(MARKER + "\n", 1)[0].rstrip("\n") + "\n\n"
    config_path.write_text(head + MARKER + "\n" + config_theme(data, faces), encoding="utf-8", newline="\n")
    (repo / "house_style.py").write_text(house_style_module(data, faces, advances), encoding="utf-8", newline="\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--tokens", type=Path, default=ROOT / "tokens.json")
    parser.add_argument("--faces", type=Path, default=ROOT / "font_faces.json")
    parser.add_argument("--advances", type=Path, default=ROOT / "cell_advances.json")
    parser.add_argument("--repo", type=Path, default=REPO, help="the folder holding .streamlit/ and house_style.py")
    parser.add_argument("--validate-only", action="store_true", help="check the contrast floors and write nothing")
    args = parser.parse_args()
    data = json.loads(args.tokens.read_text(encoding="utf-8"))
    rows = contrast_rows(data)
    failures = [row for row in rows if row["ratio"] + 1e-9 < row["minimum"]]
    for row in failures:
        print(f"{row['mode']}: {row['role']} on {row['ground']}: {row['ratio']:.4f}:1, floor {row['minimum']}:1")
    if failures:
        raise SystemExit(f"FAILED: {len(failures)} colour pairs below their floor")
    print(f"PASS: {len(rows)} declared text and boundary pairs")
    if not args.validate_only:
        write_all(data, json.loads(args.faces.read_text(encoding="utf-8")),
                  json.loads(args.advances.read_text(encoding="utf-8")), args.repo)


if __name__ == "__main__":
    main()
