"""Generate the app's theme and its own stylesheet from tokens.json.

Writes the part of .streamlit/config.toml below its marker line, and
house_style.py, which also holds what the pictures and the HTML report are drawn
in. Every colour and type size the app sets comes from tokens.json,
every face from font_faces.json and every advance from cell_advances.json
(both from build_fonts.py), so neither output is a place to choose one; two runs with the same input write the same bytes. Every
declared colour pair is held to its contrast floor first, and a pair below its
floor writes nothing. Python standard library only.
"""
import argparse
import json
import pprint
from pathlib import Path

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parent.parent
MARKER = "# Generated by tools/house_style/build_theme.py from its tokens.json. Edit that, never what follows."
FONT_ROUTE = "/zij-font/"
# The strips of section names the stylesheet holds in place, one rule set for them all; app.py
# gives each strip's container its key here. Each holds its names on one line at every usual
# window, 1366 px and up: None keeps the navigation bar's gap between them, a number is a closer
# gap for a strip of many names. A further strip is one more key.
JUMP_STRIPS = {"days-sections": None, "releaser-sections": None, "fardar-sections": 16}
# The plain link on the bar stands before the third section: Reference.
PLAIN_LINK_ORDER = 3
# Over a grid's toolbar (Streamlit's own layer for it is 101, its header's 999990).
JUMP_STRIP_LAYER = 102
# Streamlit marks an element whose run has not yet re-sent it with this attribute, and fades it
# after half a second; the page waits this long instead, so a short run shows no fade.
STALE_MARK = '[data-testid="stElementContainer"][data-stale="true"]'
STALE_FADE_DELAY = "2s"


def luminance(value):
    rgb = [int(value.lstrip("#")[i:i+2], 16) / 255 for i in (0, 2, 4)]
    linear = [v / 12.92 if v <= .04045 else ((v + .055) / 1.055) ** 2.4 for v in rgb]
    return sum(v * w for v, w in zip(linear, (.2126, .7152, .0722)))


def contrast(a, b):
    low, high = sorted((luminance(a), luminance(b)))
    return (high + .05) / (low + .05)


def mixed(foreground, ground, percent):
    """`foreground` at `percent` over `ground`, as a browser composes it."""
    channels = [(int(foreground[i:i+2], 16) * percent + int(ground[i:i+2], 16) * (100 - percent)) / 100
                for i in (1, 3, 5)]
    return "#" + "".join(f"{round(c):02X}" for c in channels)


def nav_hover(t, type_):
    """The ground under the pointer in the open navigation menu."""
    return mixed(t["brass"], t["panel"], type_["nav_hover_brass_percent"])


def palettes(t):
    return {
        "bg": t["wheel_ground"],
        "panel": t["panel"], "ink": t["ink"], "rule": t["wheel_muted"],
        "leader": t["wheel_muted"], "leader_ring": t["wheel_muted"],
        "label": t["wheel_muted"], "note": t["wheel_muted"], "axis_note": t["wheel_muted"],
        "tints": tuple(t["sign_tints"]), "shade": t["wheel_shade"], "bound_tint": t["wheel_bound_tint"],
        "axis": {0: t["steel"], 6: t["steel"], 9: t["wheel_verdigris"], 3: t["wheel_verdigris"]},
        "horizon": t["steel"], "meridian": t["wheel_verdigris"], "cusp": t["wheel_madder"],
        "badge": t["wheel_badge"], "rings": (t["ink"], t["steel"], t["wheel_madder"]),
        "now": t["wheel_madder"], "strip_tint": t["strip_tints"], "strip_other": t["strip_other"],
        # A mode whose wheel stands on another colour than its picture's ground.
        **({"face": t["wheel_face"]} if "wheel_face" in t else {}),
    }


def contrast_rows(data):
    rows = []
    def pair(mode, role, ground, fg, bg, threshold):
        rows.append(dict(mode=mode, role=role, ground=ground, foreground=fg,
                         background=bg, ratio=contrast(fg, bg), minimum=threshold))
    for mode, t in list(data["modes"].items()) + [("print", data["print"])]:
        for fg in ("ink", "muted", "muted2", "brass", "steel", "madder", "verdigris"):
            for bg in ("background", "panel", "panel2"):
                pair(mode, fg, bg, t[fg], t[bg], 4.5)
        pair(mode, "action_text", "brass", t["action_text"], t["brass"], 4.5)
        for bg in ("background", "panel", "panel2"):
            pair(mode, "field_edge", bg, t["field_edge"], t[bg], 3.0)
            pair(mode, "focus/brass", bg, t["brass"], t[bg], 3.0)
        if mode == "print":
            continue
        # A browser without light-dark() draws captions by this mix instead.
        for bg in ("background", "panel", "panel2"):
            pair(mode, "caption fallback", bg,
                 mixed(t["ink"], t[bg], data["type"]["caption_fallback_mix_percent"]), t[bg], 4.5)
        # The menu's rows under the pointer: a page, and the current page.
        for fg in ("ink", "brass"):
            pair(mode, "menu hover/" + fg, "brass tint", t[fg], nav_hover(t, data["type"]), 4.5)
        p = palettes(t)
        # Conservative: all wheel text checked against all neutral sign/shade fills.
        grounds = {"bg": p["bg"], "panel": p["panel"], "shade": p["shade"]}
        grounds.update({f"sign{i}": v for i, v in enumerate(p["tints"])})
        if "face" in p:
            grounds["face"] = p["face"]
        for role in ("ink", "label", "note", "axis_note", "badge", "horizon", "meridian", "cusp", "now"):
            for bg, val in grounds.items():
                pair(mode, "wheel/" + role, bg, p[role], val, 4.5)
        for role in ("rule", "leader", "leader_ring"):
            for bg, val in grounds.items():
                pair(mode, "wheel/" + role, bg, p[role], val, 3.0)
        pair(mode, "wheel/note", "bound_tint", p["note"], p["bound_tint"], 4.5)
        strip = dict(p["strip_tint"], other=p["strip_other"])
        for role in ("ink", "note"):
            for bg, val in strip.items():
                pair(mode, "strip/" + role, bg, p[role], val, 4.5)
    return rows


def stack(families):
    """A stack as CSS writes it: every name quoted but the generic at its end."""
    return ",".join(f'"{name}"' for name in families[:-1]) + "," + families[-1]


def picture_stack(families):
    """A stack as a picture's style attribute writes it, inside double quotes."""
    return ", ".join(f"'{name}'" for name in families[:-1]) + ", " + families[-1]


def config_theme(data, faces):
    """The theme's part of .streamlit/config.toml: both modes and their sidebars."""
    q = json.dumps
    type_ = data["type"]
    stacks = type_["stacks"]
    lines = ["[theme]",
             "font = " + q(stack(stacks["interface"])),
             "headingFont = " + q(stack(stacks["reading"])),
             "codeFont = " + q(stack(stacks["code"])),
             f"baseFontSize = {type_['base_size_px']}",
             f"baseFontWeight = {type_['base_weight']}",
             "headingFontSizes = " + q([f"{size}px" for size in type_["heading_sizes_px"]]),
             "headingFontWeights = " + q([type_["heading_weight"]] * len(type_["heading_sizes_px"])),
             "baseRadius = " + q(data["shape"]["base_radius"]),
             "buttonRadius = " + q(data["shape"]["button_radius"]),
             "showWidgetBorder = true", "showSidebarBorder = true", "linkUnderline = true"]
    for face in faces:
        if "data_base64" in face:
            continue
        lines += ["", "[[theme.fontFaces]]", "family = " + q(f'"{face["family"]}"'),
                  "url = " + q(FONT_ROUTE + face["file"]),
                  "weight = " + q(str(face["weight"])), "style = " + q(face["style"])]
        if face.get("unicode_range"):
            lines += ["unicodeRange = " + q(face["unicode_range"])]
    mapping = {"primaryColor": "brass", "backgroundColor": "background", "secondaryBackgroundColor": "panel2",
               "textColor": "ink", "borderColor": "field_edge", "dataframeBorderColor": "line_soft",
               "dataframeHeaderBackgroundColor": "panel2", "dataframeHeaderTextColor": "muted",
               "codeBackgroundColor": "panel2", "codeTextColor": "ink", "linkColor": "steel", "blueColor": "steel",
               "greenColor": "verdigris", "redColor": "madder", "orangeColor": "brass", "yellowColor": "brass"}
    for mode, t in data["modes"].items():
        lines += ["", f"[theme.{mode}]"] + [f"{key} = {q(t[token])}" for key, token in mapping.items()]
        lines += ["", f"[theme.{mode}.sidebar]", "backgroundColor = " + q(t["panel"]),
                  "secondaryBackgroundColor = " + q(t["panel2"])]
    return "\n".join(lines) + "\n"


def page_css(data, faces):
    """The page's own stylesheet: the marks face, which face a passage draws in
    by where it stands, tables and definition lists wherever a page draws them,
    and small text."""
    type_ = data["type"]
    light, dark = data["modes"]["light"], data["modes"]["dark"]
    interface, reading = stack(type_["stacks"]["interface"]), stack(type_["stacks"]["reading"])

    def both(token):
        return f"light-dark({light[token]},{dark[token]})"

    drawn = ':is([data-testid="stTable"],[data-testid="stHtml"],[data-testid="stMarkdownContainer"])'
    css = [":root{"
           f"--zij-prose-size:{type_['prose_size_px']}px;--zij-prose-line-height:{type_['prose_line_height']};"
           # What the window's height shows of a picture: all of it but the bar, the
           # strip and their gap, above and below. The natal wheel's component reads it too.
           f"--zij-wheel-window:calc(100vh - {type_['nav_height_px'] + type_['jump_strip_height_px'] + 2 * type_['jump_strip_landing_gap_px']}px);"
           f"--zij-dense-size:{type_['dense_size_px']}px;--zij-dense-line-height:{type_['dense_line_height']};"
           f"--zij-table-size:{type_['table_size_px']}px;--zij-small-size:{type_['small_size_px']}px;"
           f"--zij-definition-size:{type_['definition_size_px']}px;"
           f"--zij-definition-line-height:{type_['definition_line_height']};}}"]
    for face in faces:
        if "data_base64" in face:
            css.append(f"@font-face{{font-family:'{face['family']}';font-weight:{face['weight']};"
                       f"font-style:{face['style']};unicode-range:{face['unicode_range']};"
                       f"src:url(data:font/woff2;base64,{face['data_base64']}) format('woff2');}}")
    # Which face, by where a passage stands and by nothing else. Open on the page,
    # or in a reading container wherever it stands, the reading face; inside an
    # expander, where text is dense and lengthy, the interface face.
    text = ':is(p,li,blockquote):not([data-testid="stCaptionContainer"] *)'
    written = '[data-testid="stMarkdown"]'
    opened = f'[data-testid="stMain"] {written}'
    folded = f'[data-testid="stExpander"] {written}'
    reading_key = '[class*="st-key-reading-"]'
    css.append(f"{opened} {text},{reading_key} {text}"
               f"{{font-family:{reading};font-size:var(--zij-prose-size);line-height:var(--zij-prose-line-height);}}")
    css.append(f"{folded} {text}"
               f"{{font-family:{interface};font-size:var(--zij-dense-size);line-height:var(--zij-dense-line-height);}}")
    css.append(f"{folded} strong{{font-weight:{type_['heading_weight']};}}")
    # One measure for both, the reading container's, so a passage no container holds stops growing too.
    css.append(f"{opened} {text},{folded} {text}{{max-width:{type_['prose_measure_px']}px;}}")
    # A cell or a definition keeps its own text, wherever it stands.
    cell = ":is(td,th,dd,dt,caption)"
    css.append(f"{opened} {cell} {text},{folded} {cell} {text},{reading_key} {cell} {text}{{font:inherit;}}")
    # A table is quiet rules on the page's own ground, the header set off by its
    # ground, as near a grid as a canvas allows. Columns take their widths from
    # what they hold, so no table-layout here, and a heading stays on one line.
    css.append(f"{drawn} table{{border-collapse:collapse;}}")
    css.append(f"{drawn} :is(table,td,th){{font-size:var(--zij-table-size);line-height:{type_['table_line_height']};}}")
    css.append(f"{drawn} :is(td,th){{border:0;border-bottom:1px solid color-mix(in srgb,currentColor 25%,transparent);"
               f"border-bottom-color:{both('line_soft')};padding:{type_['table_cell_padding']};vertical-align:top;}}")
    css.append(f"{drawn} th{{background-color:{both('panel2')};font-weight:400;text-align:left;}}")
    css.append('[data-testid="stTable"] th [data-testid="stMarkdownContainer"]{white-space:nowrap;}')
    css.append('[data-testid="stTable"] th p{white-space:nowrap;}')
    # A grid's own scrollbars stay in sight, so its frame's edge reads as more to come.
    css.append(f".stDataFrameGlideDataEditor.dvn-scroller{{scrollbar-color:{both('field_edge')} transparent;}}")
    # A text table: its long cells share the page by their length, its short ones hold their line.
    css.append(f".zij-table{{overflow-x:auto;width:min(100%,{type_['text_table_max_px']}px);}}")
    css.append(".zij-short,.zij-whole{white-space:nowrap;}")
    css.append(".zij-table .zij-number{text-align:right;}")
    # A line under its row: one rule under the whole row, at its foot, and the
    # row's own values in the heavier weight, so the eye finds them first.
    css.append(".zij-spread{width:100%;}")
    css.append(f".zij-spread .zij-row-value{{font-weight:{type_['heading_weight']};}}")
    css.append(".zij-spread .zij-fill{padding:0;}")
    css.append(".zij-spread tbody tr:not(:last-child) td{border-bottom:0;}")
    css.append(".zij-spread .zij-under td{padding-top:0;}")
    css.append(f".zij-spread tbody tr:first-child td{{padding-top:{type_['table_row_gap_px']}px;}}")
    css.append(f".zij-spread tbody tr:last-child td{{padding-bottom:{type_['table_row_gap_px']}px;}}")
    css.append(".zij-under-head{margin-right:.4em;}")
    # A column holding a table is never narrower than its table can draw, so
    # side-by-side columns with no room stack, by the flex row's own wrapping.
    css.append('[data-testid="stColumn"]:has(.zij-table,[data-testid="stDataFrame"]){min-width:min-content;}')
    css.append(f"{drawn} :is(dl,dt){{margin:0;padding:0;}}")
    css.append(f"{drawn} dd{{margin:0;font-size:var(--zij-definition-size);line-height:var(--zij-definition-line-height);}}")
    css.append(f"{drawn} caption{{text-align:left;padding-bottom:8px;}}")
    # Muted text: its colour resolves in the page, under whichever theme is
    # showing, with no rerun. The line before serves a browser without light-dark().
    css.append(f'[data-testid="stCaptionContainer"],cite,.zij-locator,.zij-under-head,{drawn} :is(th,caption,dt)'
               f"{{color:color-mix(in srgb,currentColor {type_['caption_fallback_mix_percent']}%,transparent);"
               f"color:{both('muted')};opacity:1;}}")
    # Small text stays small, a caption or a citation inside reading text as well.
    css.append(f':is([data-testid="stCaptionContainer"] p,cite,.zij-locator,{drawn} caption,{drawn} dt)'
               f"{{font-family:{interface};font-size:var(--zij-small-size);font-style:normal;line-height:1.5;}}")
    css.append('[data-testid="stCaptionContainer"] p{color:inherit;opacity:1;}')
    # A dialog or a popover stands outside the element Streamlit sets its theme's
    # colour scheme on, so light-dark() there would read light under the dark
    # theme. The theme follows the computer until the reader chooses other
    # colours (the toolbar is minimal, so the sidebar's button is the only way
    # to) and this with it; a choice has its rule in PAGE_COLOUR_SCHEME.
    css.append("@media (prefers-color-scheme:dark){body{color-scheme:dark;}}")
    # The navigation bar: plain words, each arrow beside its word, a thin rule
    # under them, lined up with the page's own edges. Streamlit's bar otherwise.
    nav = '[data-testid="stTopNav"]'
    section = '[data-testid="stTopNavSection"]'
    link = '[data-testid="stTopNavDropdownLink"]'
    words = f"font-size:{type_['nav_size_px']}px;font-weight:400;"
    css.append(f"{nav}{{margin:0 {type_['page_side_padding']};padding:0;height:{type_['nav_height_px']}px;gap:{type_['nav_gap_px']}px;"
               f"align-items:center;border-bottom:1px solid {both('line')};}}")
    css.append(f"{section}{{padding:0;height:auto;gap:0;background:transparent;border:0;border-radius:0;color:{both('ink')};}}")
    css.append(f"{section} :is(p,strong){{{words}}}")
    # The arrow beside its word, its foot on the word's baseline, not centred on its height.
    css.append(f"{section} svg{{display:block;width:14px;height:14px;margin-left:-4px;transform:translateY(3px);}}")
    css.append(f'{section}:hover,{section}[aria-expanded="true"]{{background:transparent;color:{both("brass")};}}')
    css.append(f"{section}:focus-visible{{outline:2px solid {both('brass')};outline-offset:4px;}}")
    # Its open menu: the page's panel, words on a brass tint under the pointer
    # and under keyboard focus, the current page in brass and the heavier weight.
    css.append(f'[data-testid="stTopNavPopoverBody"]{{background:{both("panel")};border:1px solid {both("line")};'
               "border-radius:6px;padding:6px;}")
    css.append(f"{link}{{background:transparent;border-radius:4px;color:{both('ink')};padding:0 10px;}}")
    css.append(f"{link} p{{{words}}}")
    hover = f"light-dark({nav_hover(light, type_)},{nav_hover(dark, type_)})"
    css.append(f'{link}[aria-current="page"]{{background:transparent;}}')
    css.append(f"{link}:is(:hover,:focus,:focus-visible){{background:{hover};}}")
    css.append(f"{link}:focus-visible{{outline:2px solid {both('brass')};outline-offset:-2px;}}")
    css.append(f'{link}[aria-current="page"] p{{color:{both("brass")};font-weight:{type_["heading_weight"]};}}')
    # A page in no section is a plain link, and Streamlit puts it ahead of every
    # section whatever its place in the page list, setting each item's order on the
    # element. The bar's items are numbered from 0 with that link first, so the order of
    # the section after it stands it just before that section. An upgrade that undoes
    # this leaves the link standing first; a browser check catches it.
    plain = '[data-testid="stTopNavLink"]'
    css.append(f'{nav}>:has([data-testid="stTopNavLinkContainer"]){{order:{PLAIN_LINK_ORDER}!important;}}')
    css.append(f"{plain}{{padding:0;height:auto;gap:0;background:transparent;border-radius:0;color:{both('ink')};}}")
    css.append(f"{plain} p{{{words}}}")
    css.append(f"{plain}:hover{{background:transparent;color:{both('brass')};}}")
    css.append(f"{plain}:focus-visible{{outline:2px solid {both('brass')};outline-offset:4px;}}")
    css.append(f'{plain}[aria-current="page"]{{background:transparent;}}')
    css.append(f'{plain}[aria-current="page"] p{{color:{both("brass")};font-weight:{type_["heading_weight"]};}}')
    # The Sky alone gives its height to the view, by its own row: no other page has it,
    # and a page that refused the chart, which has no row, keeps its heading. The heading
    # stays for whatever reads the page's outline.
    sky_row = ":has(.st-key-zij-sky-controls)"
    css.append(f'[data-testid="stMainBlockContainer"]{sky_row}{{padding-top:{type_["sky_top_padding_px"]}px;}}')
    css.append(f'[data-testid="stMain"]{sky_row} :has(>.st-key-zij-sky-heading){{position:absolute;width:1px;height:1px;overflow:hidden;clip-path:inset(50%);}}')
    # Expanded, the sky's host marks its row, which stands in a narrow column: four
    # buttons in a line would run off the window, past where any scroll could reach.
    css.append('[data-zij-sky-column] [data-testid="stButtonGroup"] :has(>button){flex-wrap:wrap;}')
    # A control of more than two buttons there stands as a grid. Streamlit joins its
    # buttons by making clear the edge a chosen button's neighbours share with it, so
    # standing apart each must be given that edge again, over Streamlit's own rule.
    long_control = '[data-zij-sky-column] [role="radiogroup"]:has(>button:nth-of-type(3))'
    css.append(f'{long_control}{{display:grid;grid-template-columns:minmax(0,1fr) minmax(0,1fr);gap:4px;width:100%;}}')
    css.append(f'{long_control}>button{{width:100%;margin:0;border-radius:0.375rem;}}')
    css.append(f'{long_control}>button:not([data-selected]){{border-color:{both("field_edge")}!important;}}')
    # The strip of a page's section names, stuck under the navigation bar on an
    # opaque ground. Streamlit wraps a keyed container in a box of its own height,
    # so sticking is asked of that box, whose parent is as tall as the page; a
    # strip inside another container has no such parent and scrolls away. Above a
    # grid and its toolbar, under the bar and whatever opens over the page. Its
    # height is fixed, so a heading it jumps to can land clear of it.
    def strips(keys):
        return ":is(" + ",".join(f".st-key-{key}" for key in keys) + ")"
    strip = strips(JUMP_STRIPS)
    # One line of names, and the room above and below it that the strip's height leaves
    # inside its rule; in a window narrower than the usual ones a strip whose names do not
    # fit takes a second line, never a scroll.
    line = type_["small_size_px"] * 1.5
    room = (type_["jump_strip_height_px"] - 1 - line) / 2
    css.append(f":has(>{strip}){{position:sticky;top:{type_['nav_height_px']}px;z-index:{JUMP_STRIP_LAYER};}}")
    css.append(f"{strip}{{flex:none;min-height:{type_['jump_strip_height_px']}px;box-sizing:border-box;"
               f"padding:{room:g}px 0;justify-content:center;"
               f"background:{both('background')};border-bottom:1px solid {both('line')};}}")
    # Its words are set as a printed book's running head, small spaced capitals of
    # the text face in a muted ink, so they do not read as a web page's links: no
    # underline and not the link's colour. No rule of ours takes a link's underline
    # off but this one.
    css.append(f'[data-testid="stMain"] {strip} [data-testid="stMarkdown"] p{{display:flex;flex-wrap:wrap;'
               f'column-gap:{type_["nav_gap_px"]}px;row-gap:0;max-width:none;'
               f"margin:0;white-space:nowrap;font-family:{reading};"
               f"font-size:{type_['small_size_px']}px;letter-spacing:{type_['jump_strip_tracking_em']}em;"
               "text-transform:uppercase;line-height:1.5;}")
    for key, gap in JUMP_STRIPS.items():
        if gap is not None:
            css.append(f'[data-testid="stMain"] .st-key-{key} [data-testid="stMarkdown"] p{{column-gap:{gap}px;}}')
    css.append(f'{strip} [data-testid="stMarkdownContainer"]{{margin-bottom:0;}}')
    css.append(f"{strip} a:is(:link,:visited){{color:{both('muted')};text-decoration:none;}}")
    css.append(f"{strip} a:is(:link,:visited):is(:hover,:focus-visible){{color:{both('brass')};}}")
    css.append(f"{strip} a:focus-visible{{outline:2px solid {both('brass')};outline-offset:2px;}}")
    # Whatever is scrolled to, a heading jumped to or a field reached by the Tab
    # key, comes to rest clear of the bar and the strip. Margins and not the
    # scroller's padding, which would take in the strip's own links, so that
    # Tab onto one would scroll the page.
    landing = type_["nav_height_px"] + type_["jump_strip_height_px"] + type_["jump_strip_landing_gap_px"]
    css.append(f'[data-testid="stMain"]:has({strip}) :not({strip},{strip} *,[data-testid="stHeader"] *)'
               f"{{scroll-margin-top:{landing}px;}}")
    # The page theme's button: quiet on the panel, brass under the pointer, and
    # not left brass by the focus a press gives it, as Streamlit's own button is.
